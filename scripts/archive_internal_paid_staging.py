#!/usr/bin/env python3
"""Explicit internal paid-staging archive. Never uploads or installs anything."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import shlex
import subprocess
import sys
import tempfile
import zipfile

STAGING_REF = "gfqpbikqvdgtjjgxrkgo"
STAGING_URL = "https://" + STAGING_REF + ".supabase.co"
BUNDLE_ID = "com.ichart.app"
PAID_FLAG = "ICHART_PAID_SUBSCRIPTION"
STAGING_FLAG = "ICHART_STAGING_STOREKIT_PRODUCTS"
REQUIRED_FLAGS = {PAID_FLAG, STAGING_FLAG}
# Xcode 27 logs the same driver argv for planning, requirements and actual
# compilation. All wrappers require the literal separator before swiftc.
XCODE_SWIFT_WRAPPERS = {
    "builtin-SwiftDriver", "builtin-Swift-Compilation-Requirements", "builtin-Swift-Compilation"
}
FORBIDDEN_FLAGS = {"DEBUG", "ICHART_LOCAL_PLAN_QA", "ICHART_LOCAL_QA_PLAN_PREVIEW"}
PUBLIC_KEY = re.compile(r"sb_publishable_[A-Za-z0-9_-]{16,}\Z")


class GuardError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise GuardError(message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def read_public_key(path):
    require(path.is_file() and not path.is_symlink(), "Use a regular public-key input file.")
    require(path.stat().st_size <= 4096, "Public-key input is too large.")
    value = path.read_text().strip()
    require(PUBLIC_KEY.fullmatch(value), "Only an sb_publishable_ client key is accepted; secret, service-role and JWT keys are rejected.")
    return value


def runtime_product_ids(source):
    text = (source / "iChart/Models/IChartStoreKitProductCatalog.swift").read_text()
    branch = re.search(r"#if ICHART_STAGING_STOREKIT_PRODUCTS\s*\n(.*?)#else", text, re.DOTALL)
    require(branch is not None, "Runtime catalog must have an explicit isolated staging product branch.")
    text = branch.group(1)
    values = []
    for field in ("proMonthlyProductID", "proAnnualProductID"):
        matches = re.findall(r'\bstatic let ' + field + r' = "([^"\n]+)"', text)
        require(len(matches) == 1, "Runtime StoreKit catalog must have one literal ID per period.")
        values.append(matches[0])
    require(values[0] != values[1], "Monthly and annual product IDs must differ.")
    return values


def check_source(source, monthly, annual):
    policy = (source / "iChart/Models/IChartProductAccessPolicy.swift").read_text()
    require("#if ICHART_PAID_SUBSCRIPTION" in policy, "Paid policy compilation boundary is missing.")
    require("static let isLocalPlanQA" not in policy, "Local plan-preview override source cannot be packaged here.")
    require([monthly, annual] == runtime_product_ids(source), "Explicit Apple-reviewed product IDs must match runtime source in monthly/annual order; this script does not configure new IDs.")
    catalog = json.loads((source / "docs/internal-paid-staging-catalog.json").read_text())
    require(catalog.get("supabase_project_ref") == STAGING_REF and catalog.get("supabase_url") == STAGING_URL,
            "Staging catalog project scope changed.")
    require(catalog.get("currency") == "USD" and catalog.get("requested_prices") == {
        "monthly": {"period": "P1M", "amount": "6.99", "minor_units": 699},
        "annual": {"period": "P1Y", "amount": "60.00", "minor_units": 6000}}, "Staging price targets must remain exactly USD 6.99/month and USD 60.00/year.")
    require(catalog.get("staging_product_ids") == {"monthly": monthly, "annual": annual}, "Staging catalog product IDs do not match selected runtime IDs.")
    return catalog


def input_manifest(source):
    """Pin actual build inputs, including uncommitted files, without changing Git."""
    names = [Path("project.yml"), Path("Package.swift"), Path("docs/internal-paid-staging-catalog.json"),
             Path("iChart.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved")]
    for directory in ("iChart", "ThirdParty", "StoreKit", "scripts"):
        names.extend(p.relative_to(source) for p in (source / directory).rglob("*") if p.is_file())
    result = {}
    for name in sorted(set(names)):
        if name == Path("iChart/App/Info.plist") or "__pycache__" in name.parts or name.suffix == ".pyc":
            continue  # Info.plist is generated by XcodeGen from project.yml.
        path = source / name
        require(path.is_file() and not path.is_symlink(), "Build input missing or symlinked: " + str(name))
        result[str(name)] = sha(path.read_bytes())
    return result


def safe_environment():
    # The xcconfig supplies the only backend values. Do not inherit build flags,
    # development injection or key variables from an operator's shell.
    blocked = {"SUPABASE_URL", "SUPABASE_PUBLISHABLE_KEY", "SUPABASE_ANON_KEY",
               "SUPABASE_SERVICE_ROLE_KEY", "SUPABASE_SECRET_KEY", "SWIFT_ACTIVE_COMPILATION_CONDITIONS",
               "OTHER_SWIFT_FLAGS", "XCODE_XCCONFIG_FILE", "ICHART_INCLUDE_PERSONAL_ML_COMPARISON",
               "ICHART_PERSONAL_ML_ARTIFACT_DIR", "DYLD_INSERT_LIBRARIES"}
    return {k: v for k, v in os.environ.items() if k not in blocked and not k.startswith("SIMCTL_CHILD_")}


def run_logged(command, log, cwd, public_key):
    """No shell interpolation. Redact the public key even from Xcode diagnostics."""
    with log.open("w") as out:
        with subprocess.Popen(command, cwd=str(cwd), env=safe_environment(),
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True) as process:
            for line in process.stdout:
                out.write(line.replace(public_key, "<staging-publishable-key>"))
            code = process.wait()
    require(code == 0, "Command failed; inspect its redacted log: " + str(log))


def expand_responses(tokens, derived, depth=0):
    require(depth < 6, "Compiler response files are nested too deeply.")
    expanded = []
    for token in tokens:
        if token.startswith("@"):
            path = Path(token[1:]).resolve()
            require(path.is_relative_to(derived.resolve()), "Compiler response file is outside this build's Derived Data.")
            require(path.is_file() and path.stat().st_size <= 4 * 1024 * 1024, "Compiler response file missing or too large.")
            expanded.extend(expand_responses(shlex.split(path.read_text()), derived, depth + 1))
        else:
            expanded.append(token)
    return expanded


def compilation_evidence(log, derived, source=None):
    """Inspect actual Swift driver command tokens, not echoed build settings."""
    commands = []
    for line in log.read_text().splitlines():
        if "swiftc" not in line or "-module-name" not in line:
            continue
        try:
            tokens = shlex.split(line)
        except ValueError:
            raise GuardError("Cannot parse a Swift compiler command in archive log.")
        if "-module-name" not in tokens:
            continue
        index = tokens.index("-module-name")
        if index + 1 >= len(tokens) or tokens[index + 1] != "iChart":
            continue
        wrapper = tokens[0] if len(tokens) >= 2 and tokens[0] in XCODE_SWIFT_WRAPPERS and tokens[1] == "--" else None
        start = 2 if wrapper else 0
        require(len(tokens) > start and Path(tokens[start]).is_absolute()
                and Path(tokens[start]).name == "swiftc"
                and "/Contents/Developer/Toolchains/" in tokens[start],
                "App compiler evidence must start with the Xcode Swift driver, not echoed command text.")
        tokens = expand_responses(tokens, derived)
        require("-target" in tokens, "App compiler target is missing.")
        target_index = tokens.index("-target")
        require(target_index + 1 < len(tokens), "Incomplete compiler target.")
        target = tokens[target_index + 1]
        require("-apple-ios" in target and "simulator" not in target, "App compiler must target native iOS.")
        require("-Onone" not in tokens, "Unoptimized Debug-style app compiler invocation is rejected.")
        output_map_receipt = None
        if source is not None:
            require("-output-file-map" in tokens, "App compiler output file map is missing.")
            map_index = tokens.index("-output-file-map")
            require(map_index + 1 < len(tokens), "Incomplete compiler output map argument.")
            map_path = Path(tokens[map_index + 1]).resolve()
            require(map_path.is_relative_to(derived.resolve()) and map_path.is_file(),
                    "App compiler output map must belong to this Derived Data.")
            mapping = json.loads(map_path.read_text())
            required_sources = {(source / "iChart/Models/IChartProductAccessPolicy.swift").resolve(),
                                (source / "iChart/Models/IChartStoreKitProductCatalog.swift").resolve()}
            require(required_sources <= {Path(k).resolve() for k in mapping if k},
                    "App compiler output map is not bound to this source policy and product catalog.")
            output_map_receipt = {"path": str(map_path.relative_to(derived.resolve())), "sha256": sha(map_path.read_bytes())}
        conditions = set()
        i = 0
        while i < len(tokens):
            token = tokens[i]
            if token in {"-Xcc", "-Xllvm", "-Xlinker", "-Xfrontend"}:
                require(i + 1 < len(tokens), "Incomplete forwarded compiler argument.")
                require(token != "-Xfrontend" or not tokens[i + 1].startswith("-D"),
                        "Forwarded Swift frontend conditions are unsupported; use direct driver conditions only.")
                i += 2
                continue
            if token == "-D":
                require(i + 1 < len(tokens), "Incomplete compiler condition.")
                conditions.add(tokens[i + 1])
                i += 2
                continue
            if token.startswith("-D") and len(token) > 2:
                conditions.add(token[2:])
            i += 1
        require(REQUIRED_FLAGS <= conditions, "App Swift compiler did not select paid policy and isolated staging products.")
        require(not conditions.intersection(FORBIDDEN_FLAGS), "App Swift compiler contains a Debug or local plan-preview condition.")
        commands.append({"wrapper": wrapper or "direct-swiftc", "conditions": sorted(conditions),
                         "command_sha256": sha(line.encode()), "output_file_map": output_map_receipt})
    require(commands, "No actual iChart Swift compiler command found; build-setting text is insufficient.")
    require(any(command["wrapper"] != "builtin-Swift-Compilation-Requirements" for command in commands),
            "Swift compilation-requirements records alone do not establish an app driver/compilation invocation.")
    return commands



def build_metadata_evidence(source, derived):
    """Bind log compiler evidence to this fresh native Release archive request.

    Current Xcode manifest records command descriptions/outputs, not Swift argv.
    Actual argv are validated separately from Xcode's retained compiler log.
    """
    result = []
    for path in derived.rglob("build-request.json"):
        if not path.parent.name.endswith(".xcbuilddata"):
            continue
        request = json.loads(path.read_text())
        if Path(request.get("containerPath", "")).resolve() != (source / "iChart.xcodeproj").resolve():
            continue
        require(request.get("useDryRun") is False, "Dry-run build requests are not archive evidence.")
        parameters = request.get("parameters", {})
        require(parameters.get("configurationName") == "Release", "App build request is not Release.")
        require(request.get("schemeCommand") == "archive" and parameters.get("action") in {"install", "archive"},
                "App metadata is not an archive build request.")
        require(parameters.get("activeRunDestination", {}).get("platform") == "iphoneos",
                "App archive metadata is not native iOS.")
        manifest_path = path.with_name("manifest.json")
        manifest = json.loads(manifest_path.read_text())
        commands = []
        for name, command in manifest.get("commands", {}).items():
            if command.get("tool") != "swift-driver-compilation":
                continue
            if not re.fullmatch(r"SwiftDriver Compilation iChart normal arm64(?:e)? com\.apple\.xcode\.tools\.swift\.compiler", command.get("description", "")):
                continue
            require(":Release:SwiftDriver Compilation iChart normal " in name, "App manifest compiler is not Release.")
            required_sources = {(source / "iChart/Models/IChartProductAccessPolicy.swift").resolve(),
                                (source / "iChart/Models/IChartStoreKitProductCatalog.swift").resolve()}
            inputs = {Path(p).resolve() for p in command.get("inputs", []) if p.startswith("/")}
            require(required_sources <= inputs, "App compiler manifest does not include this source policy and product catalog.")
            outputs = command.get("outputs", [])
            require(outputs and all(Path(p).resolve().is_relative_to(derived.resolve()) for p in outputs),
                    "App compiler outputs are outside this Derived Data.")
            require(any("Release-iphoneos" in p and "iChart.build" in p for p in outputs),
                    "App compiler outputs are not native Release app outputs.")
            commands.append({"name": name, "description": command.get("description"),
                             "outputs_sha256": sha(json.dumps(outputs, sort_keys=True).encode())})
        require(commands, "Native Release archive metadata has no iChart compilation command.")
        result.append({"build_request": str(path.relative_to(derived)), "build_request_sha256": sha(path.read_bytes()),
                       "manifest": str(manifest_path.relative_to(derived)), "manifest_sha256": sha(manifest_path.read_bytes()),
                       "app_compile_commands": commands})
    require(result, "No native Release archive build-request/manifest evidence found in this Derived Data.")
    return result


def check_info(info, version, build, key):
    expected = {"CFBundleIdentifier": BUNDLE_ID, "CFBundleExecutable": "iChart", "CFBundleShortVersionString": version,
                "CFBundleVersion": build, "SupabaseURL": STAGING_URL,
                "SupabasePublishableKey": key, "SupabaseAnonKey": ""}
    for name, value in expected.items():
        require(info.get(name) == value, "Baked app setting mismatch: " + name)
    require(info.get("UIDeviceFamily") == [2], "Candidate must remain iPad-only.")
    return {"bundle_id": BUNDLE_ID, "version": version, "build": build, "url": STAGING_URL,
            "publishable_key_sha256": sha(key.encode()), "legacy_anon_empty": True, "device_family": [2]}


def reject_personal_assets(names):
    forbidden = ("PersonalMLComparison", "PersonalVisualEncoderResearch", "private-profile.json")
    require(not any(any(part in name for part in forbidden) for name in names), "Personal comparison resources are present in the package.")


def verify_archive(archive, version, build, key):
    apps = list((archive / "Products/Applications").glob("*.app"))
    require(len(apps) == 1 and apps[0].name == "iChart.app", "Archive must contain exactly iChart.app.")
    info = plistlib.loads((apps[0] / "Info.plist").read_bytes())
    reject_personal_assets(str(p.relative_to(apps[0])) for p in apps[0].rglob("*"))
    result = check_info(info, version, build, key)
    executable = apps[0] / info["CFBundleExecutable"]
    require(executable.is_file(), "Archive executable is missing.")
    result["executable_sha256"] = sha(executable.read_bytes())
    return result


def verify_ipa(ipa, version, build, key):
    with zipfile.ZipFile(ipa) as package:
        names = package.namelist()
        require(len(names) == len(set(names)), "IPA contains duplicate ZIP entries.")
        infos = [name for name in names if re.fullmatch(r"Payload/[^/]+\.app/Info\.plist", name)]
        require(infos == ["Payload/iChart.app/Info.plist"], "IPA must contain exactly Payload/iChart.app.")
        reject_personal_assets(names)
        result = check_info(plistlib.loads(package.read(infos[0])), version, build, key)
        executable = "Payload/iChart.app/iChart"
        require(executable in names and package.getinfo(executable).file_size > 0, "IPA app executable is missing or empty.")
        result["executable_sha256"] = sha(package.read(executable))
    result["ipa_sha256"] = sha(ipa.read_bytes())
    return result


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("action", choices=("plan", "archive", "verify"))
    p.add_argument("--project-ref", required=True)
    p.add_argument("--publishable-key-file", type=Path, required=True)
    p.add_argument("--version", required=True)
    p.add_argument("--build", required=True)
    p.add_argument("--monthly-product-id", required=True, help="Explicit Apple-reviewed ID; must match runtime source.")
    p.add_argument("--annual-product-id", required=True, help="Explicit Apple-reviewed ID; must match runtime source.")
    p.add_argument("--output-dir", type=Path, required=True, help="Fresh local directory outside source/iCloud for archive action.")
    p.add_argument("--ipa", type=Path, help="Also verify this exported IPA; verify action only.")
    return p


def main(argv=None):
    args = parser().parse_args(argv)
    source = Path(__file__).resolve().parent.parent
    require(args.project_ref == STAGING_REF, "This command accepts only the explicit internal staging project ref.")
    require(re.fullmatch(r"[0-9]+\.[0-9]+(?:\.[0-9]+)?", args.version), "Provide the Apple-verified numeric version explicitly.")
    require(re.fullmatch(r"[1-9][0-9]*", args.build) and int(args.build) > 172, "Provide an unused Apple-verified build greater than local preview 172.")
    require(args.ipa is None or args.action == "verify", "--ipa is available only for verify.")
    key = read_public_key(args.publishable_key_file)
    catalog = check_source(source, args.monthly_product_id, args.annual_product_id)
    output = args.output_dir.resolve()
    require(not output.is_relative_to(source) and not source.is_relative_to(output), "Output must be separate from the source checkout.")
    require(not {"Documents", "Desktop", "Mobile Documents", "CloudStorage"}.intersection(output.parts), "Use local build storage outside iCloud Documents/Desktop/CloudStorage.")
    archive, derived = output / "iChart.xcarchive", output / "DerivedData"
    pin_path = output / "source-inputs.json"
    plan = {"audience": "internal TestFlight only", "url": STAGING_URL,
            "publishable_key_sha256": sha(key.encode()), "version": args.version, "build": args.build,
            "swift_conditions": sorted(REQUIRED_FLAGS), "personal_ml_comparison": "NO", "configuration": "Release",
            "product_ids": {"monthly": args.monthly_product_id, "annual": args.annual_product_id},
            "requested_prices": catalog["requested_prices"], "apple_catalog_readback": catalog.get("apple_catalog_readback"),
            "apple_price_verified_by_packaging": False, "actual_storekit_prices_verified": False,
            "key_project_membership_verified": False, "archive": str(archive),
            "limits": "Packaging checks do not establish Apple prices, key project membership, hosted policy, signatures, upload, or saved iPad content."}
    if args.action == "plan":
        print(json.dumps(plan, indent=2))
        return
    if args.action == "archive":
        require(not output.exists(), "Archive output already exists; choose a fresh directory without deleting old evidence.")
        output.mkdir(parents=True, mode=0o700)
        before = input_manifest(source)
        git_state = {}
        for name, command in {"commit": ["rev-parse", "HEAD"], "tree": ["rev-parse", "HEAD^{tree}"],
                              "status": ["status", "--porcelain=v1"]}.items():
            git_state[name] = subprocess.check_output(["git", "--no-optional-locks", "-C", str(source)] + command,
                                                      text=True, env=safe_environment()).strip()
        (output / "source-state.json").write_text(json.dumps(git_state, indent=2) + "\n")
        pin_path.write_text(json.dumps(before, indent=2) + "\n")
        # XcodeGen generates only the local project and Info.plist from unchanged project.yml.
        run_logged(["xcodegen", "generate", "--spec", str(source / "project.yml")], output / "xcodegen.log", source, key)
        config_text = ("SUPABASE_URL = https:/$()/" + STAGING_REF + ".supabase.co\n"
                       "SUPABASE_PUBLISHABLE_KEY = " + key + "\nSUPABASE_ANON_KEY =\n"
                       "SWIFT_ACTIVE_COMPILATION_CONDITIONS = $(inherited) " + " ".join(sorted(REQUIRED_FLAGS)) + "\nOTHER_SWIFT_FLAGS = $(inherited)\n"
                       "ICHART_INCLUDE_PERSONAL_ML_COMPARISON = NO\nMARKETING_VERSION = " + args.version +
                       "\nCURRENT_PROJECT_VERSION = " + args.build + "\n")
        with tempfile.NamedTemporaryFile(mode="w", suffix=".xcconfig", prefix="staging-", dir=output, delete=False) as config:
            config.write(config_text)
            config_path = Path(config.name)
        try:
            command = ["xcodebuild", "archive", "-project", str(source / "iChart.xcodeproj"), "-scheme", "iChart",
                       "-configuration", "Release", "-destination", "generic/platform=iOS", "-xcconfig", str(config_path),
                       "-derivedDataPath", str(derived), "-clonedSourcePackagesDirPath", str(output / "SourcePackages"),
                       "-archivePath", str(archive), "-resultBundlePath", str(output / "archive.xcresult"),
                       "-onlyUsePackageVersionsFromResolvedFile"]
            # Retain a reproducible redacted command; public key itself is baked into the app as designed.
            (output / "archive-command.json").write_text(json.dumps(command, indent=2) + "\n")
            run_logged(command, output / "archive.log", source, key)
        finally:
            config_path.unlink(missing_ok=True)
        require(before == input_manifest(source), "Source/package inputs changed during archive; retain artifacts and investigate.")
    else:
        require(pin_path.is_file(), "Missing source pin from this packaging command.")
        require(json.loads(pin_path.read_text()) == input_manifest(source), "Current inputs differ from the archive source pin.")
    plan["build_metadata"] = build_metadata_evidence(source, derived)
    plan["compiler_commands"] = compilation_evidence(output / "archive.log", derived, source)
    plan["archive_log_sha256"] = sha((output / "archive.log").read_bytes())
    plan["archive_verification"] = verify_archive(archive, args.version, args.build, key)
    if args.ipa:
        plan["ipa_verification"] = verify_ipa(args.ipa, args.version, args.build, key)
    (output / "internal-paid-staging-verification.json").write_text(json.dumps(plan, indent=2) + "\n")
    print(json.dumps({"verified": True, "receipt": str(output / "internal-paid-staging-verification.json"),
                      "url": STAGING_URL, "version": args.version, "build": args.build}))


if __name__ == "__main__":
    try:
        main()
    except (GuardError, OSError, ValueError, KeyError, zipfile.BadZipFile) as error:
        print("Internal staging packaging failed: " + str(error), file=sys.stderr)
        sys.exit(1)
